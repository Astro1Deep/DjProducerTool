# Helper function to get the correct string
get_localized_string() {
  local key="$1"
  # Ensure uppercase for variable lookup (bash 3.2 compatible)
  local lang_prefix="L_$(echo "${DJPT_CURRENT_LANG:-EN}" | tr '[:lower:]' '[:upper:]')"
  local var_name="${lang_prefix}_${key}"
  # Use indirect expansion to get the value of the variable named by $var_name
  # Fallback to English if the Spanish version is not defined for some reason
  if [ -n "${!var_name:-}" ]; then
    printf "%s" "${!var_name}"
  else
    local en_var_name="L_EN_${key}"
    printf "%s" "${!en_var_name}"
  fi
}
